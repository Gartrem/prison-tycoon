const aliases={A:'А',B:'В',C:'С',E:'Е',H:'Н',K:'К',M:'М',O:'О',P:'Р',T:'Т',X:'Х',Y:'У'};
const rowsFor=ch=>ch===' '||ch==='\u00ad'?null:(glyphs[aliases[ch]||ch]||glyphs['?']);
const units=ch=>ch===' '?3:(rowsFor(ch)?.[0].length||5)+1.5;
export const blockWidth=(text,size)=>[...text.toUpperCase()].reduce((sum,ch)=>sum+units(ch),0)*size/9;
export function blockPath(ctx,text,w,h){
 const chars=[...text.toUpperCase()],total=chars.reduce((s,ch)=>s+units(ch),0);
 const step=Math.min(h/9,Math.max(0,w-1)/Math.max(1,total)),left=(w-total*step)/2;
 let cursor=left;ctx.beginPath();
 for(const ch of chars){
  const rows=rowsFor(ch);
  if(rows){
   const rowStep=rows.length>7?step*.8:step;
   const top=Math.max(0,(h-7*step)/2-(rows.length-7)*rowStep);
   rows.forEach((row,yy)=>{for(let xx=0;xx<row.length;xx++)if(row[xx]==='1'){
    // Expand strokes inward: heavy lettering without rounded font contours.
    ctx.rect(cursor+xx*step,top+yy*rowStep,1.85*step,1.65*rowStep);
   }});
  }
  cursor+=units(ch)*step;
 }
}
